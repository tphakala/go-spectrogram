var (
	fontOnce sync.Once
	fontBits []byte
)

// fontData returns the inflated 96*fontY glyph table. The blob is a
// compile-time constant, so failure to inflate is a programmer error.
func fontData() []byte {
	fontOnce.Do(func() {
		r, err := zlib.NewReader(bytes.NewReader(fontBlob[:]))
		if err != nil {
			panic("sox: corrupt embedded font: " + err.Error())
		}
		defer r.Close()
		fontBits, err = io.ReadAll(r)
		if err != nil {
			panic("sox: corrupt embedded font: " + err.Error())
		}
		if len(fontBits) != 96*fontY {
			panic("sox: embedded font has unexpected size")
		}
	})
	return fontBits
}
